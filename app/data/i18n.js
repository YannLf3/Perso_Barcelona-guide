// Fonction pour obtenir la traduction d'une clé
/**
 * Fonction de traduction (Helper)
 * Elle permet de récupérer une chaîne de caractères à partir d'une clé (ex: "navIntro")
 * et d'une langue. Elle gère automatiquement les replis (fallbacks) si la traduction manque.
 *
 * @param {string} key - La clé de traduction (ex: "contactButton")
 * @param {string} lang - Le code langue (en, fr, es, it)
 * @returns {string} Le texte traduit ou la clé par défaut
 */
export function t(key, lang = "en") {
  // On récupère l'objet de traduction pour la langue demandée, ou l'anglais par défaut
  const locale = I18N[lang] || I18N.en;

  // GESTION DE LA COMPATIBILITÉ (Legacy)
  // Si on demande encore l'ancienne clé "introTitle", on fusionne les nouvelles clés
  // introTitleBefore et introTitleAccent pour ne pas casser les anciens scripts.
  if (key === "introTitle") {
    const before = locale.introTitleBefore ?? I18N.en.introTitleBefore ?? "";
    const accent = locale.introTitleAccent ?? I18N.en.introTitleAccent ?? "";
    return `${before}${accent}`;
  }

  // 1. On cherche la clé dans la langue demandée
  if (locale[key] != null && locale[key] !== "") {
    return locale[key];
  }

  // 2. FALLBACK : Si on ne trouve pas, on cherche dans la langue par défaut (anglais)
  if (I18N.en[key] != null && I18N.en[key] !== "") {
    return I18N.en[key];
  }

  // 3. ULTIME RECOURS : On renvoie le nom de la clé elle-même (mieux qu'un texte vide)
  return key;
}

/**
 * Générateur de titre dynamique (DOM Manipulation)
 * Contrairement à t(), cette fonction ne renvoie pas une chaîne mais un élément HTML complet.
 * On l'utilise car le titre d'intro nécessite une mise en forme spécifique (un <span> avec une classe).
 *
 * @param {string} lang - La langue actuelle
 * @returns {HTMLHeadingElement} Un élément <h2> prêt à être inséré dans le DOM
 */
export function buildIntroTitle(lang = "en") {
  const locale = I18N[lang] || I18N.en;

  // On crée l'élément conteneur
  const title = document.createElement("h2");

  const before =
    locale.introTitleBefore ?? I18N.en.introTitleBefore ?? "Welcome to ";
  const accent =
    locale.introTitleAccent ?? I18N.en.introTitleAccent ?? "Barcelona";

  // On ajoute le début du texte (ex: "Bienvenue à ")
  title.append(before);

  // On crée un <span> pour le mot mis en avant (ex: "Barcelone")
  const accentSpan = document.createElement("span");
  accentSpan.className = "title-accent";

  // Sécurité stylistique : On force la couleur ici pour s'assurer que le design
  // reste lisible même si d'autres styles CSS complexes s'appliquent sur les h2.
  accentSpan.style.color = "#d4780a";
  accentSpan.style.webkitTextFillColor = "#d4780a"; // Pour le support de certains navigateurs
  accentSpan.textContent = accent; // textContent est plus sûr que innerHTML (évite XSS)

  // On assemble le tout
  title.append(accentSpan);

  return title;
}
